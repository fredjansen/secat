(function () {
  var C = window.CATALOG;
  var status = document.getElementById("export-status");

  var features = [];
  C.categories.forEach(function (c) {
    c.features.forEach(function (f) { features.push({ category: c, feature: f }); });
  });

  // Plain records: answers keyed by facet name
  function records() {
    return C.sources.map(function (s) {
      var answers = {};
      features.forEach(function (x) { answers[x.feature.name] = s.answers[x.feature.id]; });
      return {
        id: s.id,
        name: s.name,
        url: s.url,
        confidence: s.confidence,
        notes: s.notes,
        references: s.references,
        answers: answers
      };
    });
  }

  function propertySchema(f) {
    var p = { description: f.question };
    var list = Array.isArray(f.expected_values) ? f.expected_values : null;
    if (f.data_type === "array") {
      p.type = ["array", "null"];
      p.items = list ? { type: "string", "enum": list } : { type: "string" };
    } else if (f.data_type === "number") {
      p.type = ["number", "null"];
    } else {
      p.type = ["string", "null"];
      if (list) p["enum"] = list.concat([null]);
    }
    return p;
  }

  function jsonSchema() {
    var props = {};
    features.forEach(function (x) { props[x.feature.name] = propertySchema(x.feature); });
    return {
      "$schema": "https://json-schema.org/draft/2020-12/schema",
      title: C.title,
      type: "object",
      required: ["sources"],
      properties: {
        sources: {
          type: "array",
          items: {
            type: "object",
            required: ["id", "name", "url", "answers"],
            properties: {
              id: { type: "integer" },
              name: { type: "string" },
              url: { type: "string", format: "uri" },
              confidence: { type: "string", "enum": ["high", "medium", "low"] },
              notes: { type: "string" },
              references: { type: "array", items: { type: "string", format: "uri" } },
              answers: { type: "object", properties: props, additionalProperties: false }
            }
          }
        }
      }
    };
  }

  function exportJson() {
    var doc = {
      title: C.title,
      generated_on: C.generated_on,
      conventions: C.conventions,
      schema: jsonSchema(),
      sources: records()
    };
    return JSON.stringify(doc, null, 2);
  }

  function esc(s) {
    return String(s).replace(/[&<>"]/g, function (ch) {
      return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[ch];
    });
  }

  function cell(v) {
    if (v === null) return '<td class="na">n/a</td>';
    if (Array.isArray(v)) return "<td>" + esc(v.join(", ")) + "</td>";
    return "<td>" + esc(v) + "</td>";
  }

  function exportHtml() {
    var parts = [];
    parts.push('<!DOCTYPE html>\n<html lang="en">\n<head>\n<meta charset="utf-8">\n<meta name="viewport" content="width=device-width, initial-scale=1">');
    parts.push("<title>" + esc(C.title) + "</title>");
    parts.push("<style>body{font-family:system-ui,Segoe UI,Arial,sans-serif;margin:24px;color:#1c2430}h1{color:#0b3d6e}" +
      "h2{color:#0b3d6e;margin-top:32px}.wrap{overflow-x:auto}table{border-collapse:collapse;font-size:13px;min-width:100%}" +
      "th,td{border:1px solid #d8dee6;padding:6px 8px;text-align:left;vertical-align:top}th{background:#eef2f7}" +
      ".na{color:#8a94a3}a{color:#0b3d6e}</style>\n</head>\n<body>");
    parts.push("<h1>" + esc(C.title) + "</h1>");
    parts.push("<p>Exported on " + new Date().toISOString().slice(0, 10) + ". Data generated on " + esc(C.generated_on) +
      ". Answers were generated by an AI model; n/a means not available.</p>");

    C.categories.forEach(function (c) {
      parts.push("<h2>" + c.id + ". " + esc(c.name) + "</h2>\n<div class=\"wrap\"><table><thead><tr><th>Source</th>");
      c.features.forEach(function (f) { parts.push("<th>" + esc(f.name) + "</th>"); });
      parts.push("</tr></thead><tbody>");
      C.sources.forEach(function (s) {
        parts.push('<tr><td><a href="' + esc(s.url) + '">' + esc(s.name) + "</a></td>");
        c.features.forEach(function (f) { parts.push(cell(s.answers[f.id])); });
        parts.push("</tr>");
      });
      parts.push("</tbody></table></div>");
    });
    parts.push("</body>\n</html>\n");
    return parts.join("\n");
  }

  // JSON value -> Python literal
  function py(v, indent) {
    var pad = new Array(indent + 1).join("    ");
    var inner = pad + "    ";
    if (v === null) return "None";
    if (v === true) return "True";
    if (v === false) return "False";
    if (typeof v === "number") return String(v);
    if (typeof v === "string") return JSON.stringify(v);
    if (Array.isArray(v)) {
      if (!v.length) return "[]";
      if (v.every(function (x) { return typeof x !== "object" || x === null; })) {
        return "[" + v.map(function (x) { return py(x, 0); }).join(", ") + "]";
      }
      return "[\n" + v.map(function (x) { return inner + py(x, indent + 1); }).join(",\n") + ",\n" + pad + "]";
    }
    var keys = Object.keys(v);
    if (!keys.length) return "{}";
    return "{\n" + keys.map(function (k) {
      return inner + JSON.stringify(k) + ": " + py(v[k], indent + 1);
    }).join(",\n") + ",\n" + pad + "}";
  }

  function exportPython() {
    var categories = C.categories.map(function (c) {
      return {
        id: c.id,
        name: c.name,
        features: c.features.map(function (f) {
          return { id: f.id, name: f.name, data_type: f.data_type, question: f.question, expected_values: f.expected_values };
        })
      };
    });
    return [
      '"""' + C.title + ".",
      "",
      "Exported on " + new Date().toISOString().slice(0, 10) + " from the online catalog. Data generated on " + C.generated_on + ".",
      "Answers were generated by an AI model. None means not available, [] means not applicable.",
      "",
      "Usage:",
      "    import grey_literature_catalog as glc",
      '    glc.filter_sources("Website type", "forum")',
      '"""',
      "",
      "CATEGORIES = " + py(categories, 0),
      "",
      "SOURCES = " + py(records(), 0),
      "",
      "",
      "def get_source(name):",
      '    """Return the source whose name matches (case-insensitive), or None."""',
      "    name = name.lower()",
      '    return next((s for s in SOURCES if s["name"].lower() == name), None)',
      "",
      "",
      "def filter_sources(feature, value):",
      '    """Return the sources whose answer to `feature` is or contains `value`."""',
      "    result = []",
      "    for s in SOURCES:",
      '        answer = s["answers"].get(feature)',
      "        if answer == value or (isinstance(answer, list) and value in answer):",
      "            result.append(s)",
      "    return result",
      "",
      "",
      'if __name__ == "__main__":',
      '    print(f"{len(SOURCES)} sources, {sum(len(c[\'features\']) for c in CATEGORIES)} features")',
      "    for s in SOURCES:",
      '        print(f"- {s[\'name\']}: {s[\'url\']}")',
      ""
    ].join("\n");
  }

  function download(content, filename, type) {
    var blob = new Blob([content], { type: type + ";charset=utf-8" });
    var url = URL.createObjectURL(blob);
    var a = document.createElement("a");
    a.href = url;
    a.download = filename;
    document.body.appendChild(a);
    a.click();
    a.remove();
    setTimeout(function () { URL.revokeObjectURL(url); }, 1000);
    status.textContent = "Downloaded " + filename + ".";
  }

  var exporters = {
    json: function () { download(exportJson(), "grey-literature-catalog.json", "application/json"); },
    html: function () { download(exportHtml(), "grey-literature-catalog.html", "text/html"); },
    python: function () { download(exportPython(), "grey_literature_catalog.py", "text/x-python"); }
  };

  document.querySelectorAll("[data-export]").forEach(function (btn) {
    btn.addEventListener("click", function () { exporters[btn.getAttribute("data-export")](); });
  });
})();
